#!/usr/bin/env python3
"""Generate offline LuCI brand data from IEEE MA-L and pinned Simple Icons.

Normal builds use the committed generated module; no network is used on routers.
Re-run with --check to verify the generated file against cached source files.
"""
import argparse
import base64
import csv
import hashlib
import io
import json
from pathlib import Path
import re
import urllib.request
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
CACHE = ROOT / 'vendor/brand-data'
OUTPUT = ROOT / 'htdocs/luci-static/resources/unifi/brand-data.js'
SOURCES = ROOT / 'research/brand-data-sources.json'
ICON_VERSION = '16.37.0'
ICON_BASE = f'https://raw.githubusercontent.com/simple-icons/simple-icons/{ICON_VERSION}'
OUI_URL = 'https://standards-oui.ieee.org/oui/oui.csv'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check committed outputs without downloading')
    parser.add_argument('--refresh', action='store_true', help='refresh upstream data and source checksums')
    args = parser.parse_args()
    if args.check and args.refresh:
        parser.error('--check and --refresh are mutually exclusive')
    definitions = json.loads((ROOT / 'tools/brand-definitions.json').read_text())
    known = json.loads(SOURCES.read_text()) if SOURCES.exists() else {}
    sources = {}

    def read_source(url, filename):
        cached = CACHE / filename
        if not cached.exists() or args.refresh:
            if args.check:
                raise SystemExit(f'Missing cached source {cached}; run this script without --check first.')
            CACHE.mkdir(parents=True, exist_ok=True)
            request = urllib.request.Request(url, headers={'User-Agent': 'luci-theme-unifi-brand-builder'})
            with urllib.request.urlopen(request, timeout=90) as response:
                content = response.read()
            digest = hashlib.sha256(content).hexdigest()
            if not args.refresh and url in known and known[url]['sha256'] != digest:
                raise SystemExit(f'Upstream source changed: {url}; use --refresh to update intentionally.')
            cached.write_bytes(content)
        content = cached.read_bytes()
        digest = hashlib.sha256(content).hexdigest()
        if not args.refresh and url in known and known[url]['sha256'] != digest:
            raise SystemExit(f'Cached source checksum mismatch: {cached}')
        sources[url] = {'sha256': digest, 'bytes': len(content)}
        return content

    brands, groups = {}, {}
    for key, definition in definitions.items():
        brand = {k: v for k, v in definition.items() if k not in ('icon', 'organizations')}
        if definition.get('icon'):
            slug = definition['icon']
            svg = ET.fromstring(read_source(f'{ICON_BASE}/icons/{slug}.svg', slug + '.svg'))
            paths = [p.attrib['d'] for p in svg.findall('{http://www.w3.org/2000/svg}path')]
            if not paths or not all(re.fullmatch(r'[MmZzLlHhVvCcSsQqTtAaEe0-9.,+\s-]+', p) for p in paths):
                raise SystemExit(f'Unsupported SVG path in {slug}')
            brand['paths'] = paths
        brands[key] = brand
        groups[key] = []

    registry = read_source(OUI_URL, 'oui.csv').decode('utf-8-sig')
    patterns = [(key, re.compile(item['organizations'])) for key, item in definitions.items()]
    for row in csv.DictReader(io.StringIO(registry)):
        prefix = row.get('Assignment', '').strip().upper()
        if row.get('Registry') != 'MA-L' or not re.fullmatch(r'[0-9A-F]{6}', prefix):
            continue
        for key, pattern in patterns:
            if pattern.search(row['Organization Name']):
                groups[key].append(prefix)
                break
    prefixes = {key: base64.b64encode(b''.join(bytes.fromhex(p) for p in sorted(set(values)))).decode()
                for key, values in groups.items() if values}
    payload = {'iconVersion': ICON_VERSION, 'brands': brands, 'prefixes': prefixes}
    module = ("/* Generated by tools/generate_brands.py.\n"
              " * Brand SVG paths: Simple Icons (CC0-1.0); trademarks belong to their owners.\n"
              " * MAC prefixes: IEEE Registration Authority MA-L registry. */\n"
              "'use strict';\n'require baseclass';\n\nreturn baseclass.extend("
              + json.dumps(payload, ensure_ascii=False, separators=(',', ':')) + ');\n')
    license_text = read_source(f'{ICON_BASE}/LICENSE.md', 'Simple-Icons-LICENSE.md')
    license_path = ROOT / 'root/usr/share/licenses/luci-theme-unifi/Simple-Icons-CC0.txt'
    source_text = json.dumps(sources, indent=2, sort_keys=True) + '\n'
    if args.check:
        if OUTPUT.read_text() != module or SOURCES.read_text() != source_text or license_path.read_bytes() != license_text:
            raise SystemExit('Brand data, provenance or license is out of date.')
    else:
        OUTPUT.write_text(module)
        SOURCES.write_text(source_text)
        license_path.write_bytes(license_text)
    count = sum(len(set(values)) for values in groups.values())
    print(f'{"Verified" if args.check else "Generated"} {len(brands) - 1} brands, {count} prefixes, {len(module.encode()):,} bytes')


if __name__ == '__main__':
    main()
